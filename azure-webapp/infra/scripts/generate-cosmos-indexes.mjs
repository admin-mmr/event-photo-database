#!/usr/bin/env node
/**
 * generate-cosmos-indexes.mjs — derive `infra/cosmos-indexes.json` from the
 * GCP side's `cloud-webapp/infra/firestore.indexes.json`.
 *
 * Why generate rather than hand-maintain: the Azure copy was hand-written once
 * and immediately fell behind — it still carried 3 composite indexes while
 * Firestore had grown to 12, missing both queue-drain indexes. A missing index
 * is not a slow query on either cloud, it is a FAILED_PRECONDITION that 500s
 * every drain tick (which is exactly how this broke on GCP at first cutover).
 *
 * Usage:
 *   node generate-cosmos-indexes.mjs           # write the file
 *   node generate-cosmos-indexes.mjs --check   # exit 1 if stale (for CI)
 *
 * ## The two things this is NOT a mechanical translation of
 *
 * 1. **Firestore appends the `__name__` tiebreak to every composite index
 *    implicitly; Cosmos requires it spelled out.** Our paged queries order by
 *    `(<field>, DOC_ID)` — decision D8's keyset paging depends on that total
 *    order — so for paged containers the trailing `/id` is added here. A
 *    verbatim translation would omit it and every gallery page would fail.
 *
 * 2. **Cosmos indexes all paths by default**, including large arrays that are
 *    payload rather than query keys. The queue batch documents inline their work
 *    list (up to ENQUEUE_CAP = 1500 items), and a drain tick rewrites the doc on
 *    every chunk — indexing that array would burn write RU for nothing on the
 *    exact containers that write most often. Those paths are excluded.
 *
 * Direction variants need no special handling: Firestore already enumerates both
 * ascending and descending per field (same reverse-scan constraint), so the
 * declared set maps 1:1 onto the ORDER BY directions the app actually issues.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(HERE, '../../../cloud-webapp/infra/firestore.indexes.json');
const TARGET = resolve(HERE, '../cosmos-indexes.json');

/**
 * Containers whose queries carry the document-id tiebreak, so their composite
 * indexes need a trailing `/id`. Keep in sync with the `orderBy(DOC_ID, …)`
 * call sites — today only the gallery pages (`routes/gallery.ts`).
 */
const PAGED_BY_ID = new Set(['photos']);

/**
 * Payload paths never used in a filter or sort. Excluded to keep write RU off
 * large inline arrays. `/*` still indexes everything else.
 */
const UNINDEXED_PATHS = {
  duplicateRemovalBatches: ['/pending/*', '/pendingSweep/*'],
  folderRebuildBatches: ['/pending/*', '/inProgress/*'],
};

const ORDER = { ASCENDING: 'ascending', DESCENDING: 'descending' };

function build() {
  const src = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const containers = {};

  for (const index of src.indexes ?? []) {
    const name = index.collectionGroup;
    const composite = index.fields.map((f) => {
      const order = ORDER[f.order];
      if (!order) throw new Error(`unsupported order '${f.order}' on ${name}.${f.fieldPath}`);
      return { path: `/${f.fieldPath}`, order };
    });

    if (PAGED_BY_ID.has(name)) {
      // The id tiebreak follows the direction of the sort field it breaks ties
      // for — see gallery.ts: `.orderBy(spec.field, spec.dir).orderBy(DOC_ID, spec.dir)`.
      composite.push({ path: '/id', order: composite[composite.length - 1].order });
    }

    containers[name] ??= {
      indexingMode: 'consistent',
      automatic: true,
      includedPaths: [{ path: '/*' }],
      excludedPaths: [
        { path: '/_etag/?' },
        ...(UNINDEXED_PATHS[name] ?? []).map((path) => ({ path })),
      ],
      compositeIndexes: [],
    };
    containers[name].compositeIndexes.push(composite);
  }

  return {
    _comment:
      'GENERATED by infra/scripts/generate-cosmos-indexes.mjs from ' +
      'cloud-webapp/infra/firestore.indexes.json — do not edit by hand. ' +
      'Cosmos indexing policies are PER CONTAINER, so this is a map rather than ' +
      'one policy. Apply each with: az cosmosdb sql container update -a <acct> ' +
      '-g <rg> -d <db> -n <container> --idx @<(jq .containers.<container> ' +
      'infra/cosmos-indexes.json). Re-run the generator after changing ' +
      'firestore.indexes.json; `--check` fails CI when the two drift.',
    _source: 'cloud-webapp/infra/firestore.indexes.json',
    containers,
  };
}

const rendered = `${JSON.stringify(build(), null, 2)}\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== rendered) {
    console.error(
      'cosmos-indexes.json is stale relative to firestore.indexes.json.\n' +
        'Run: node azure-webapp/infra/scripts/generate-cosmos-indexes.mjs',
    );
    process.exit(1);
  }
  console.log('cosmos-indexes.json is up to date.');
} else {
  writeFileSync(TARGET, rendered);
  console.log(`wrote ${TARGET}`);
}
