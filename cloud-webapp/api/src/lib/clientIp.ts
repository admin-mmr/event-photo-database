/**
 * clientIp.ts — the caller's IP, in a form a bot cannot forge, for per-IP
 * rate limiting (middleware/rateLimit.ts `guestIpRateLimit`).
 *
 * Do NOT use `req.ip` for anything abuse-related. With `trust proxy` on it is
 * the LEFTMOST X-Forwarded-For entry, and the api is reachable two ways:
 *
 *   via Firebase Hosting (every browser):  XFF = "<client>, <Google front end>"
 *     Hosting REPLACES any X-Forwarded-For / Fastly-Client-IP the client sent
 *     (verified 2026-11-02 with a forged-header probe), so <client> is real.
 *   direct to *.run.app (public, by necessity — see CLAUDE.md):
 *                                          XFF = "<anything the caller sent>, <caller>"
 *     Cloud Run only APPENDS the connecting address, so the leftmost entry is
 *     whatever the bot chose, and a bot rotating it would get a fresh quota
 *     per request.
 *
 * So: if the LAST hop is a Google front end, the client is the hop before it;
 * otherwise the last hop is the caller itself. "Google front end" means
 * goog.json minus cloud.json (lib/googleFrontEndRanges.ts, regenerated by
 * infra/scripts/refresh-google-front-end-ranges.sh) — a Google Cloud VM is in
 * goog.json too, and must not be trusted to name its own client.
 *
 * IPv6 clients are keyed by their /64: one subscriber is routinely handed a
 * whole /64, so a per-address key would be trivially rotated.
 *
 * Residual: a request relayed by a non-Cloud Google service that lets the
 * caller set headers (e.g. Apps Script UrlFetch) can still choose its key.
 * That costs a bot real Google quota per request; reCAPTCHA still applies.
 */

import { BlockList, isIP } from 'node:net';
import type { Request } from 'express';

import { GOOGLE_FRONT_END_RANGES } from './googleFrontEndRanges.js';

const googleFrontEnds = new BlockList();
for (const cidr of GOOGLE_FRONT_END_RANGES) {
  const [addr, bits] = cidr.split('/') as [string, string];
  googleFrontEnds.addSubnet(addr, Number(bits), isIP(addr) === 6 ? 'ipv6' : 'ipv4');
}

export function isGoogleFrontEnd(ip: string): boolean {
  const v = isIP(ip);
  return v !== 0 && googleFrontEnds.check(ip, v === 6 ? 'ipv6' : 'ipv4');
}

/** Strips the IPv4-mapped prefix (`::ffff:1.2.3.4` → `1.2.3.4`). */
function unmap(ip: string): string {
  return ip.startsWith('::ffff:') && isIP(ip.slice(7)) === 4 ? ip.slice(7) : ip;
}

/** IPv4 as-is; IPv6 collapsed to its /64 (`2001:db8:1:2::/64`). */
export function rateLimitKeyForIp(ip: string): string {
  if (isIP(ip) !== 6) return ip;
  const [head, tail] = ip.split('::') as [string, string | undefined];
  const left = head ? head.split(':') : [];
  const right = tail ? tail.split(':') : [];
  const groups = tail === undefined ? left : [...left, ...Array(8 - left.length - right.length).fill('0'), ...right];
  const prefix = groups.slice(0, 4).map((g) => (parseInt(g || '0', 16) || 0).toString(16));
  return `${prefix.join(':')}::/64`;
}

export interface ClientIp {
  /** The client's address, or undefined when it cannot be trusted. */
  readonly ip: string | undefined;
  /** `hosting` — via a Google front end; `direct` — caller connected itself;
   *  `local` — no X-Forwarded-For (dev / tests). */
  readonly via: 'hosting' | 'direct' | 'local';
  /** True when what we would call the client is itself a Google front end —
   *  the range list is stale or the chain is odd. Never rate-limit on it: it
   *  would lump every Hosting visitor into one bucket. */
  readonly suspect?: true;
}

export function clientIp(req: Pick<Request, 'headers' | 'socket'>): ClientIp {
  const raw = req.headers['x-forwarded-for'];
  const header = Array.isArray(raw) ? raw.join(',') : raw;
  const hops = (header ?? '')
    .split(',')
    .map((h) => unmap(h.trim()))
    .filter((h) => isIP(h) !== 0);

  if (hops.length === 0) {
    const sock = req.socket?.remoteAddress;
    return { ip: sock ? unmap(sock) : undefined, via: 'local' };
  }

  const last = hops[hops.length - 1]!;
  if (isGoogleFrontEnd(last)) {
    const client = hops.length >= 2 ? hops[hops.length - 2]! : undefined;
    return client === undefined || isGoogleFrontEnd(client)
      ? { ip: undefined, via: 'hosting', suspect: true }
      : { ip: client, via: 'hosting' };
  }
  return { ip: last, via: 'direct' };
}
