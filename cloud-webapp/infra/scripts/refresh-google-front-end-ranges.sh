#!/usr/bin/env bash
#
# refresh-google-front-end-ranges.sh — regenerates
# api/src/lib/googleFrontEndRanges.ts from Google's published IP lists.
#
# Why: the api finds the real client IP from X-Forwarded-For (lib/clientIp.ts).
# Through the Firebase Hosting rewrite the LAST hop is a Google front end and
# the hop before it is the client; called directly on *.run.app the last hop IS
# the client. Telling the two apart needs "is this a Google front end?", which
# is goog.json MINUS cloud.json — goog.json alone also covers Google Cloud
# customer ranges, and a bot on a cheap GCE VM would then be trusted to name
# its own client IP.
#
# Run it when clientIp logs "unrecognized front-end hop" (Hosting moved to a
# range this list doesn't have), or every few months. Review the diff, run the
# api tests, commit.
#
# Usage: ./infra/scripts/refresh-google-front-end-ranges.sh

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$ROOT/api/src/lib/googleFrontEndRanges.ts"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

curl -fsS https://www.gstatic.com/ipranges/goog.json -o "$TMP/goog.json"
curl -fsS https://www.gstatic.com/ipranges/cloud.json -o "$TMP/cloud.json"

python3 -I - "$TMP" "$OUT" <<'EOF'
import ipaddress, json, sys

tmp, out = sys.argv[1], sys.argv[2]

def load(name):
    j = json.load(open(f"{tmp}/{name}"))
    nets = [ipaddress.ip_network(p.get("ipv4Prefix") or p.get("ipv6Prefix")) for p in j["prefixes"]]
    return nets, j.get("creationTime", "?")

goog, goog_time = load("goog.json")
cloud, cloud_time = load("cloud.json")

result = []
for g in goog:
    pieces = [g]
    for c in cloud:
        if c.version != g.version:
            continue
        nxt = []
        for p in pieces:
            if p.subnet_of(c):
                continue
            if c.subnet_of(p):
                nxt.extend(p.address_exclude(c))
            else:
                nxt.append(p)
        pieces = nxt
    result.extend(pieces)

v4 = list(ipaddress.collapse_addresses(n for n in result if n.version == 4))
v6 = list(ipaddress.collapse_addresses(n for n in result if n.version == 6))
if len(v4) < 50:
    sys.exit(f"refusing to write: only {len(v4)} IPv4 prefixes — the source lists look wrong")

lines = [
    "// GENERATED by infra/scripts/refresh-google-front-end-ranges.sh — do not edit by hand.",
    f"// Source: goog.json ({goog_time}) minus cloud.json ({cloud_time}).",
    "// Google-owned ranges that are NOT Google Cloud customer ranges: the front ends",
    "// that sit between a Firebase Hosting visitor and Cloud Run (see lib/clientIp.ts).",
    "",
    "export const GOOGLE_FRONT_END_RANGES: readonly string[] = [",
]
lines += [f"  '{n}'," for n in v4 + v6]
lines += ["];", ""]
open(out, "w").write("\n".join(lines))
print(f"wrote {out}: {len(v4)} IPv4 + {len(v6)} IPv6 prefixes")
EOF
